#!/usr/bin/env node
/** Write a system's Tailwind v4 / shadcn theme from its tokens.css.
 *  node system_theme.mjs assets/systems/<name>   writes <name>/theme.tailwind.css
 *  The file imports tokens.css and maps the system's roles onto the color, radius and font names Tailwind utilities
 *  and shadcn/ui components use (bg-primary, text-muted-foreground, border-input, rounded-lg), so a Tailwind or shadcn
 *  project takes the system without renaming anything. Dark mode follows the system's own [data-theme] rules. */
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {resolve, join, basename} from 'node:path';

const dir = resolve(process.argv[2] || '');
const tokensFile = join(dir, 'tokens.css');
if (!existsSync(tokensFile)) { console.error('Usage: node system_theme.mjs assets/systems/<name>'); process.exit(2); }
const tokens = readFileSync(tokensFile, 'utf8');
const has = v => new RegExp(`${v}\\s*:`).test(tokens);
const map = {
  background: '--bg', foreground: '--text', card: '--surface', 'card-foreground': '--text', popover: '--surface', 'popover-foreground': '--text',
  primary: '--accent', 'primary-foreground': '--on-accent', secondary: '--surface-2', 'secondary-foreground': '--text',
  muted: '--surface-2', 'muted-foreground': '--text-3', accent: '--hover', 'accent-foreground': '--text',
  destructive: '--bad', 'destructive-foreground': '--on-bad', success: '--ok', warning: '--warn', info: '--info',
  border: '--line', input: '--line-strong', ring: '--accent',
  sidebar: '--surface', 'sidebar-foreground': '--text', 'sidebar-primary': '--accent', 'sidebar-primary-foreground': '--on-accent',
  'sidebar-accent': '--hover', 'sidebar-accent-foreground': '--text', 'sidebar-border': '--line', 'sidebar-ring': '--accent',
  ...Object.fromEntries([1, 2, 3, 4, 5].map(i => [`chart-${i}`, `--chart-${i}`])),
};
// A dark-first system is dark unless the page opts into light, so Tailwind's dark: must match that default too.
const topLevel = tokens.replace(/\/\*[\s\S]*?\*\//g, '').replace(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, '');
const darkFirst = [...topLevel.matchAll(/([^{}]*)\{([^{}]*)\}/g)].some(([, selector, body]) => /:root/.test(selector) && !/@media/.test(selector) && /color-scheme\s*:\s*dark/.test(body));
const darkVariant = darkFirst ? ':root:not([data-theme=light]), :root:not([data-theme=light]) *' : '[data-theme=dark], [data-theme=dark] *';
const lines = Object.entries(map).filter(([, v]) => has(v)).map(([k, v]) => `  --color-${k}: var(${v});`);
const radius = [['sm', '--r-sm'], ['md', '--r-md'], ['lg', '--r-lg']].filter(([, v]) => has(v)).map(([k, v]) => `  --radius-${k}: var(${v});`);
const fonts = [['sans', '--font'], ['mono', '--font-mono']].filter(([, v]) => has(v)).map(([k, v]) => `  --font-${k}: var(${v});`);
const ease = [['out', '--ease-out'], ['in-out', '--ease-in-out']].filter(([, v]) => has(v)).map(([k, v]) => `  --ease-${k}: var(${v});`);
const out = `/* ${basename(dir)} for Tailwind v4 and shadcn/ui. Generated by scripts/system_theme.mjs from tokens.css; do not edit by hand.
   @import "tailwindcss"; then @import "./theme.tailwind.css"; ${darkFirst ? 'dark by default; set data-theme="light" on <html> for the light theme.' : 'set data-theme="dark" on <html> for the dark theme.'} */
@import "./tokens.css";
@custom-variant dark (&:where(${darkVariant}));

@theme inline {
${[...lines, ...radius, ...fonts, ...ease].join('\n')}
}
`;
writeFileSync(join(dir, 'theme.tailwind.css'), out);
console.log(`Wrote ${join(dir, 'theme.tailwind.css')} (${lines.length} colors, ${radius.length} radii, ${fonts.length} fonts)`);
